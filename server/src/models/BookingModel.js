const mongoose = require('mongoose')
const { Schema } = mongoose

// The six booking statuses from the team contract, in the order a booking moves through them.
const STATUSES = ['pending', 'accepted', 'declined', 'paid', 'in-progress', 'completed']

const bookingSchema = new Schema(
  {
    ownerId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    sitterId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
    petIds: [{ type: Schema.Types.ObjectId, ref: 'Pet' }],

    startDate: { type: Date, required: true },
    endDate: { type: Date, required: true },

    totalPrice: { type: Number, required: true, min: 0 },

    status: { type: String, enum: STATUSES, default: 'pending' },

    // NEW (proposed): every request sent together shares the same groupId.
    // Generated by the server when the requests are created, never typed by the user,
    // e.g. crypto.randomUUID(). Used to auto-decline the other sitters once one is paid.
    groupId: { type: String, required: true, index: true },

    // NEW (proposed): the owner's label for the trip, e.g. "Taiwan Trip".
    // Same value on every booking in the group.
    groupName: { type: String, trim: true, maxlength: 60 }
  },
  { timestamps: true }
)

// A booking can't end before it starts.
bookingSchema.pre('validate', function () {
  if (this.startDate && this.endDate && this.endDate < this.startDate) {
    this.invalidate('endDate', 'endDate must be on or after startDate')
  }
})

module.exports = mongoose.model('Booking', bookingSchema)
module.exports.STATUSES = STATUSES
